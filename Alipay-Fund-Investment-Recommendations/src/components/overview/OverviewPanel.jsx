/**
 * OverviewPanel — 组合趋势总览看板
 *
 * 相比单只基金详情，这里把基金池里所有基金放在同一坐标系里比较：
 *   1. 归一化净值走势（100 起算）+ 等权组合曲线 + 沪深300 基准
 *   2. 每只基金近 N 日涨跌排行与风险指标
 *   3. 板块热度（东方财富行业板块涨幅榜 + 主力净流入）
 *   4. DeepSeek 生成的组合级配置策略（无 Key 时用本地引擎降级）
 */

import { useState, useEffect, useMemo, useCallback, useRef } from 'react';
import ReactECharts from 'echarts-for-react';
import useFundStore from '../../store/useFundStore';
import { fetchFundHistory } from '../../services/fundService';
import { fetchOverviewMarket } from '../../services/overviewService';
import { buildOverview } from '../../utils/overviewEngine';
import { fetchOverviewStrategy } from '../../services/aiService';
import './overview.css';

// 基金曲线配色刻意避开紫色系，否则会和「组合等权」那条主线撞色
const SERIES_COLORS = ['#38bdf8', '#f59e0b', '#22c55e', '#ec4899', '#fb923c', '#a3e635'];
const PERIODS = [
  { days: 10, label: '近10日' },
  { days: 20, label: '近20日' },
];
const HEAT_TONE = { 火热: 'hot', 偏热: 'warm', 分化: 'mixed', 偏冷: 'cool', 冷清: 'cold' };

const fmtPct = (v, digits = 2) => `${v >= 0 ? '+' : ''}${Number(v).toFixed(digits)}%`;
const fmtYi = (v) => `${v >= 0 ? '+' : ''}${(Number(v) / 1e8).toFixed(2)}亿`;
const toneOf = (v) => (v > 0 ? 'text-rise' : v < 0 ? 'text-fall' : 'text-secondary');

/** 顶部指标卡 */
function StatCard({ label, value, sub, tone }) {
  return (
    <div className="ov-stat">
      <span className="ov-stat-label">{label}</span>
      <span className={`ov-stat-value ${tone || ''}`}>{value}</span>
      {sub ? <span className="ov-stat-sub">{sub}</span> : null}
    </div>
  );
}

/** 建议动作徽章 */
function ActionBadge({ action }) {
  const cls =
    action === '加仓' ? 'badge-add' : action === '减仓' ? 'badge-cut' : action === '观望' ? 'badge-watch' : 'badge-hold';
  return <span className={`ov-action ${cls}`}>{action}</span>;
}

export default function OverviewPanel() {
  const funds = useFundStore((s) => s.funds);
  const [days, setDays] = useState(10);
  const [raw, setRaw] = useState({ fundHistories: [], indexTrend: null, sectors: [] });
  const [loading, setLoading] = useState(true);
  const [strategy, setStrategy] = useState(null);
  const [aiLoading, setAiLoading] = useState(false);
  const [error, setError] = useState('');
  // 记录已生成过策略的数据指纹，避免基金池加载过程中重复调用大模型
  const strategyKeyRef = useRef('');
  const timerRef = useRef(null);
  const autoGeneratedRef = useRef(false);

  const codesKey = funds.map((f) => f.code).join(',');

  // 拉取基金历史 + 大盘 + 板块
  useEffect(() => {
    let cancelled = false;

    async function load() {
      setLoading(true);
      setError('');
      try {
        const [market, ...histories] = await Promise.all([
          fetchOverviewMarket(30),
          ...funds.map(async (f) => {
            const history = await fetchFundHistory(f.code, '1m');
            return { code: f.code, name: f.name, history: history || [] };
          }),
        ]);

        if (cancelled) return;
        setRaw({
          fundHistories: histories.filter((h) => h.history.length > 0),
          indexTrend: market.indexTrend,
          sectors: market.sectors,
        });
      } catch (err) {
        if (!cancelled) setError(err?.message || '总览数据加载失败');
      } finally {
        if (!cancelled) setLoading(false);
      }
    }

    load();
    return () => {
      cancelled = true;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [codesKey]);

  const overview = useMemo(
    () =>
      buildOverview({
        fundHistories: raw.fundHistories,
        indexTrend: raw.indexTrend,
        sectorHeat: raw.sectors,
        days,
      }),
    [raw, days]
  );

  // 概览数据变化后生成策略
  // 基金池是逐只异步加入的，加载过程中 codesKey 会多次变化。
  // 这里用「加载完成 + 2.5s 防抖 + 每次挂载只自动生成一次」，
  // 保证一次进页面只消耗一次 DeepSeek 调用；想刷新数据点「重新生成」。
  useEffect(() => {
    if (loading || !overview.hasData) return;
    if (autoGeneratedRef.current) return;

    const key = `${codesKey}|${days}|${overview.dates[0]}~${overview.dates[overview.dates.length - 1]}`;
    if (strategyKeyRef.current === key) return;

    clearTimeout(timerRef.current);
    timerRef.current = setTimeout(() => {
      if (autoGeneratedRef.current) return;
      autoGeneratedRef.current = true;
      strategyKeyRef.current = key;
      // 不做 unmount 取消：StrictMode 下 effect 会双跑，若第一次请求被 cleanup 丢弃、
      // 第二次又被守卫拦住，就永远拿不到策略。
      setAiLoading(true);
      fetchOverviewStrategy(overview).then((s) => {
        setStrategy(s);
        setAiLoading(false);
      });
    }, 2500);

    return () => clearTimeout(timerRef.current);
  }, [overview, codesKey, days, loading]);

  const refreshStrategy = useCallback(async () => {
    if (!overview.hasData) return;
    setAiLoading(true);
    const s = await fetchOverviewStrategy(overview);
    setStrategy(s);
    setAiLoading(false);
  }, [overview]);

  const chartOption = useMemo(() => {
    if (!overview.hasData) return null;
    const { dates, funds: fundList, benchmark, portfolio } = overview;

    const series = [
      {
        name: '组合等权',
        type: 'line',
        data: portfolio?.series || [],
        smooth: true,
        symbol: 'none',
        itemStyle: { color: '#818cf8' },
        lineStyle: { width: 3.2, color: '#818cf8' },
        areaStyle: {
          color: {
            type: 'linear',
            x: 0,
            y: 0,
            x2: 0,
            y2: 1,
            colorStops: [
              { offset: 0, color: 'rgba(129, 140, 248, 0.28)' },
              { offset: 1, color: 'rgba(129, 140, 248, 0.01)' },
            ],
          },
        },
        z: 10,
      },
      ...(benchmark
        ? [
            {
              name: benchmark.name,
              type: 'line',
              data: benchmark.series,
              smooth: true,
              symbol: 'none',
              itemStyle: { color: '#94a3b8' },
              lineStyle: { width: 1.6, color: '#94a3b8', type: 'dashed' },
              z: 8,
            },
          ]
        : []),
      ...fundList.map((f, i) => {
        const color = SERIES_COLORS[i % SERIES_COLORS.length];
        return {
          name: f.name,
          type: 'line',
          data: f.series,
          smooth: true,
          symbol: 'none',
          itemStyle: { color },
          lineStyle: { width: 1.8, color, opacity: 0.9 },
          z: 6,
        };
      }),
    ];

    return {
      backgroundColor: 'transparent',
      grid: { left: '2%', right: '2%', bottom: '6%', top: 46, containLabel: true },
      legend: {
        data: series.map((s) => s.name),
        textStyle: { color: 'rgba(148, 163, 184, 0.85)', fontSize: 11 },
        itemWidth: 14,
        itemHeight: 8,
        top: 6,
        icon: 'roundRect',
      },
      tooltip: {
        trigger: 'axis',
        backgroundColor: 'rgba(15, 17, 23, 0.96)',
        borderColor: 'rgba(99, 102, 241, 0.3)',
        borderWidth: 1,
        textStyle: { color: '#e2e8f0', fontSize: 12 },
        formatter: (params) => {
          const date = params[0]?.axisValue || '';
          const rows = params
            .filter((p) => p.value != null)
            .map((p) => {
              const diff = p.value - 100;
              const color = diff >= 0 ? '#ef4444' : '#22c55e';
              return `<div style="display:flex;justify-content:space-between;gap:16px;line-height:1.7">
                <span style="color:${p.color}">${p.seriesName}</span>
                <span style="color:${color};font-weight:600">${diff >= 0 ? '+' : ''}${diff.toFixed(2)}%</span>
              </div>`;
            })
            .join('');
          return `<div style="font-size:11px;opacity:.65;margin-bottom:4px">${date}（以 100 起算）</div>${rows}`;
        },
      },
      xAxis: {
        type: 'category',
        data: dates,
        boundaryGap: false,
        axisLine: { lineStyle: { color: 'rgba(148, 163, 184, 0.15)' } },
        axisLabel: {
          color: 'rgba(148, 163, 184, 0.6)',
          fontSize: 11,
          formatter: (v) => `${v.slice(5, 7)}/${v.slice(8, 10)}`,
        },
        axisTick: { show: false },
      },
      yAxis: {
        type: 'value',
        scale: true,
        axisLine: { show: false },
        axisLabel: {
          color: 'rgba(148, 163, 184, 0.6)',
          fontSize: 11,
          formatter: (v) => v.toFixed(1),
        },
        splitLine: { lineStyle: { color: 'rgba(148, 163, 184, 0.06)' } },
      },
      series,
    };
  }, [overview]);

  const rankedFunds = useMemo(
    () => [...overview.funds].sort((a, b) => b.score - a.score),
    [overview.funds]
  );

  const maxAbsReturn = useMemo(
    () => Math.max(1, ...rankedFunds.map((f) => Math.abs(f.periodReturn))),
    [rankedFunds]
  );

  /* ===== 渲染 ===== */

  if (loading) {
    return (
      <div className="ov-loading">
        <div className="loading-spinner" />
        <span>正在汇总基金池、大盘与板块数据…</span>
      </div>
    );
  }

  if (funds.length === 0) {
    return (
      <div className="ov-empty">
        <span>基金池还是空的，先在左侧搜索并添加基金，这里会汇总它们的走势。</span>
      </div>
    );
  }

  if (!overview.hasData) {
    return (
      <div className="ov-empty">
        <span>{error || '净值数据不足，无法绘制组合趋势，请稍后刷新重试。'}</span>
      </div>
    );
  }

  const { portfolio, benchmark, sector } = overview;

  return (
    <div className="overview">
      {/* 指标卡 */}
      <div className="ov-stats">
        <StatCard
          label={`组合近${days}日`}
          value={fmtPct(portfolio.periodReturn)}
          sub={`等权组合 · ${overview.funds.length} 只基金`}
          tone={toneOf(portfolio.periodReturn)}
        />
        <StatCard
          label={benchmark ? `${benchmark.name}同期` : '大盘同期'}
          value={benchmark ? fmtPct(benchmark.periodReturn) : '--'}
          sub={benchmark ? `最大回撤 ${benchmark.maxDrawdown.toFixed(2)}%` : '基准数据缺失'}
          tone={benchmark ? toneOf(benchmark.periodReturn) : ''}
        />
        <StatCard
          label="相对基准超额"
          value={benchmark ? `${portfolio.excess >= 0 ? '+' : ''}${portfolio.excess.toFixed(2)}pp` : '--'}
          sub={benchmark ? (portfolio.excess >= 0 ? '跑赢基准' : '跑输基准') : ''}
          tone={benchmark ? toneOf(portfolio.excess) : ''}
        />
        <StatCard
          label="组合最大回撤"
          value={`${portfolio.maxDrawdown.toFixed(2)}%`}
          sub={`年化波动 ${portfolio.volatility.toFixed(2)}%`}
          tone="text-warning"
        />
        <StatCard
          label="与大盘相关性"
          value={portfolio.corr.toFixed(2)}
          sub={portfolio.corr > 0.8 ? '同涨同跌，分散不足' : '有一定分散效果'}
        />
      </div>

      {/* 趋势图 + 侧栏 */}
      <div className="ov-main">
        <div className="ov-card ov-trend-card">
          <div className="ov-card-head">
            <h3 className="ov-card-title">组合走势对比（归一化）</h3>
            <div className="period-tabs">
              {PERIODS.map((p) => (
                <button
                  key={p.days}
                  className={`period-tab ${days === p.days ? 'active' : ''}`}
                  onClick={() => setDays(p.days)}
                >
                  {p.label}
                </button>
              ))}
            </div>
          </div>
          <div className="ov-chart">
            <ReactECharts
              option={chartOption}
              style={{ height: '100%', width: '100%' }}
              opts={{ renderer: 'canvas' }}
              notMerge
            />
          </div>
        </div>

        <div className="ov-side">
          {/* 单基排行 */}
          <div className="ov-card">
            <h3 className="ov-card-title">近{days}日基金表现</h3>
            <div className="ov-rank-list">
              {rankedFunds.map((f) => (
                <div key={f.code} className="ov-rank-item">
                  <div className="ov-rank-top">
                    <span className="ov-rank-name" title={f.name}>
                      {f.name}
                    </span>
                    <span className={`ov-rank-ret ${toneOf(f.periodReturn)}`}>{fmtPct(f.periodReturn)}</span>
                  </div>
                  <div className="ov-rank-bar">
                    <div
                      className={`ov-rank-fill ${f.periodReturn >= 0 ? 'rise' : 'fall'}`}
                      style={{ width: `${(Math.abs(f.periodReturn) / maxAbsReturn) * 100}%` }}
                    />
                  </div>
                  <div className="ov-rank-meta">
                    <span>评分 {f.score}</span>
                    <span>回撤 {f.maxDrawdown.toFixed(2)}%</span>
                    <span>相关性 {f.corr.toFixed(2)}</span>
                  </div>
                </div>
              ))}
            </div>
          </div>

          {/* 板块热度 */}
          <div className="ov-card">
            <div className="ov-card-head">
              <h3 className="ov-card-title">板块热度</h3>
              <span className={`ov-heat-tag ${HEAT_TONE[sector.label] || 'mixed'}`}>{sector.label}</span>
            </div>
            <div className="ov-sector-summary">
              涨幅均值 <span className={toneOf(sector.avgChange)}>{fmtPct(sector.avgChange)}</span>
              <span className="ov-dot">·</span>
              主力净流入 <span className={toneOf(sector.netInflow)}>{fmtYi(sector.netInflow)}</span>
            </div>
            {sector.top.length > 0 ? (
              <div className="ov-sector-list">
                {sector.top.map((s) => (
                  <div key={s.code || s.name} className="ov-sector-item">
                    <span className="ov-sector-name">{s.name}</span>
                    <span className={`ov-sector-chg ${toneOf(s.change)}`}>{fmtPct(s.change)}</span>
                    <span className={`ov-sector-flow ${toneOf(s.mainInflow)}`}>{fmtYi(s.mainInflow)}</span>
                  </div>
                ))}
              </div>
            ) : (
              <div className="ov-sector-empty">板块数据暂不可用</div>
            )}
          </div>
        </div>
      </div>

      {/* AI 策略 */}
      <div className="ov-card ov-ai-card">
        <div className="ov-card-head">
          <h3 className="ov-card-title">
            AI 组合策略
            <span className={`ov-source ${strategy?.isAI ? 'is-ai' : ''}`}>
              {aiLoading ? '生成中…' : strategy?.isAI ? 'DeepSeek' : '本地分析'}
            </span>
          </h3>
          <button className="ov-refresh" onClick={refreshStrategy} disabled={aiLoading}>
            {aiLoading ? '分析中…' : '重新生成'}
          </button>
        </div>

        {!strategy ? (
          <div className="ov-ai-loading">
            <div className="loading-spinner" />
            <span>{aiLoading ? '正在综合大盘、板块与基金走势…' : '正在汇总数据，稍候生成策略…'}</span>
          </div>
        ) : (
          <>
            <div className="ov-verdict">
              <span className="ov-verdict-icon">{strategy.verdictIcon}</span>
              <div className="ov-verdict-main">
                <span className={`ov-verdict-text ${strategy.verdictColor === 'rise' ? 'text-rise' : strategy.verdictColor === 'fall' ? 'text-fall' : ''}`}>
                  {strategy.verdict}
                </span>
                <span className="ov-verdict-conf">置信度 {strategy.confidence}%</span>
              </div>
              <div className="ov-conf-bar">
                <div className="ov-conf-fill" style={{ width: `${strategy.confidence}%` }} />
              </div>
            </div>

            <p className="ov-ai-summary">{strategy.summary}</p>
            {strategy.marketView ? (
              <p className="ov-ai-market">
                <span className="ov-ai-label">大盘与板块</span>
                {strategy.marketView}
              </p>
            ) : null}

            {strategy.allocations.length > 0 ? (
              <div className="ov-alloc-list">
                {strategy.allocations.map((a) => (
                  <div key={a.code || a.name} className="ov-alloc-item">
                    <div className="ov-alloc-head">
                      <span className="ov-alloc-name">{a.name}</span>
                      <code className="ov-alloc-code">{a.code}</code>
                      <ActionBadge action={a.action} />
                      <span className="ov-alloc-weight">{a.weight}</span>
                    </div>
                    <p className="ov-alloc-reason">{a.reason}</p>
                  </div>
                ))}
              </div>
            ) : null}

            {strategy.risks.length > 0 ? (
              <div className="ov-risks">
                {strategy.risks.map((r) => (
                  <div key={r} className="ov-risk-item">
                    <span className="ov-risk-dot" />
                    {r}
                  </div>
                ))}
              </div>
            ) : null}

            <div className="ov-ai-foot">
              更新于 {strategy.updatedAt} · 仅供参考，不构成投资建议
            </div>
          </>
        )}
      </div>
    </div>
  );
}
