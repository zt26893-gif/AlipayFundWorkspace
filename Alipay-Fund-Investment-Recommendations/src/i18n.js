export function translate(lang, key, vars) {
  const table = DICT[lang] || DICT.zh;
  let text = table[key] ?? DICT.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

